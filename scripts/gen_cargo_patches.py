#!/usr/bin/env python3
"""Regenerates the [patch.crates-io] block in .cargo/config.toml.

talos-agent depends directly on a handful of ROS 2 generated Rust message
crates (nav_msgs, geometry_msgs, ...). Those crates depend on each other
(e.g. geometry_msgs -> std_msgs, builtin_interfaces), so cargo needs a
[patch.crates-io] entry for the full transitive closure, not just the
crates talos-agent names directly. This script computes that closure from
the pre-generated Rust bindings in the Pixi environment and rewrites
.cargo/config.toml accordingly, instead of hand-maintaining the list.
"""

import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INSTALL_DIR = ROOT / ".pixi" / "envs" / "default" / "share"
AGENT_MANIFEST = ROOT / "talos-agent" / "Cargo.toml"
OUTPUT = ROOT / ".cargo" / "config.toml"

HEADER = (
    "# AUTO-GENERATED by scripts/gen-cargo-patches.sh - do not hand edit.\n"
    "# Patches crates-io with the pre-generated ROS 2 Rust message bindings\n"
    "# shipped by the robostack-lyrical conda packages in the Pixi env.\n"
)


def crate_manifest(name: str) -> Path:
    return INSTALL_DIR / name / "rust" / "Cargo.toml"


def load_deps(name: str) -> set[str]:
    manifest = crate_manifest(name)
    if not manifest.is_file():
        return set()
    with manifest.open("rb") as f:
        data = tomllib.load(f)
    return set(data.get("dependencies", {}))


def main() -> None:
    with AGENT_MANIFEST.open("rb") as f:
        agent_deps = set(tomllib.load(f)["dependencies"])

    # Seed the closure with whichever direct deps are actually ROS-generated
    # crates (i.e. the conda packages ship Rust bindings for them).
    roots = {name for name in agent_deps if crate_manifest(name).is_file()}
    if not roots:
        raise SystemExit(
            f"no ROS crates found among {AGENT_MANIFEST}'s dependencies "
            f"under {INSTALL_DIR} - has `pixi install` been run?"
        )

    closure = set(roots)
    frontier = set(roots)
    while frontier:
        next_frontier: set[str] = set()
        for name in frontier:
            for dep in load_deps(name):
                if dep not in closure and crate_manifest(dep).is_file():
                    closure.add(dep)
                    next_frontier.add(dep)
        frontier = next_frontier

    lines = [HEADER]
    for name in sorted(closure):
        rel_path = crate_manifest(name).relative_to(ROOT).parent
        lines.append(f"[patch.crates-io.{name}]\n")
        lines.append(f'path = "{rel_path}"\n')
        lines.append("\n")

    OUTPUT.write_text("".join(lines).rstrip() + "\n")
    print(f"wrote {len(closure)} patch entries to {OUTPUT}")


if __name__ == "__main__":
    main()
